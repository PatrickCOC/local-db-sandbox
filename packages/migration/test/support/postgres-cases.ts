/*
 * Schema changes that the PostgreSQL generator is tried with (D-039), each as
 * migrations: `base` makes the schema to start from, and `change` what it is
 * to become. `sql` is the migration that is expected to be generated from
 * the one schema to the other, statement by statement.
 *
 * Both are SQL that PostgreSQL itself takes: the same cases are run on a
 * PostgreSQL server outside the repository, where the generated migration
 * and `change` have to leave the same catalog.
 */

export interface RoundTripCase {
  title: string;
  base: string;
  change: string;
  /** The statements expected, in their order. */
  sql: string[];
  /** The segments expected: how each is run and how many statements it has. Without it: one transaction of them all. */
  segments?: string[];
  /** Generated only on the caller's word that the rows fit. */
  assumeValidData?: true;
}

