import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join, relative, resolve } from "node:path";
import { importTypeorm, toDatabaseDocument } from "../../import-typeorm/src/index.ts";
import type { ImportResult } from "../../import-typeorm/src/index.ts";
import { DEFAULT_MAX_FILE_SIZE_MB, DatabaseFormatError, DirectoryStorageAdapter, assertWithinSizeLimit, createDatabase, databaseFormatFor, mergeSchemas, mergeTypes, sameDatabaseSchema } from "../../storage-json/src/index.ts";
import type { DatabaseFormat } from "../../storage-json/src/index.ts";
import { NestSandboxError, findProjectRoot } from "./nest-sandbox.ts";
import type { NestSandboxConfig } from "./nest-sandbox.ts";
import { databaseSchema } from "./typeorm-runtime.ts";

export const SANDBOX_DIRECTORY = ".local-db-sandbox";
export const DEFAULT_NEST_SANDBOX_PORT = 3001;
/** The database of a new project: a database directory in the project root. */
const DEFAULT_DATABASE = "sandbox.db";
/** The database of projects set up by earlier versions: a single file in the project root. */
const SINGLE_FILE_DATABASE = "sandbox.db.json";
const SCRIPT_NAME = "sandbox";
/** Starts the sandbox once. */
const RUN_COMMAND = `node ${SANDBOX_DIRECTORY}/sandbox.server.ts`;
/** Starts the sandbox and restarts it when the application's sources change. */
const SCRIPT_COMMAND = `${RUN_COMMAND} --watch`;

const SERVER_FILE = `// Generated by "local-db-sandbox init-nest". Run that command again instead of editing this file.
//
// Starts this project's own entry point in sandbox mode: the same application,
// with TypeORM's default data source replaced by the JSON database named in
// sandbox.config.json, listening on the sandbox port.
//
//   npm run ${SCRIPT_NAME}    restarts the sandbox when the application's sources change (--watch)
//   ${RUN_COMMAND}    starts it once
import { join } from "node:path";
import { runNestSandbox } from "local-db-sandbox";

await runNestSandbox(join(import.meta.dirname, "sandbox.config.json"));
`;

export interface InitNestOptions {
  /** The application's entry point. Default: the one named by nest-cli.json, or src/main.ts. */
  entry?: string;
  /** Directory that relative paths are resolved against. Default: the current working directory. */
  cwd?: string;
  /** Sandbox port. Default: the port of an existing sandbox.config.json, or 3001. */
  port?: number;
  /**
   * The database: a database directory, or a single file when the path ends
   * in `.json`. Default: the database of an existing sandbox.config.json;
   * otherwise a sandbox.db.json that is already in the project root;
   * otherwise the directory sandbox.db in the project root.
   */
  database?: string;
  /** File or folder to read TypeORM entities from. Default: the entry point's folder. */
  entities?: string;
}

export interface InitNestResult {
  /** The project root (the folder of the nearest package.json). Other paths are relative to it. */
  root: string;
  entry: string;
  rootModule: { name: string; from: string | undefined };
  /** Source files that call `TypeOrmModule.forRoot` or `forRootAsync`. */
  typeormRoots: string[];
  entities: string;
  import: ImportResult;
  database: {
    /** The file or directory. */
    file: string;
    format: DatabaseFormat;
    created: boolean;
    addedCollections: string[];
    /** A directory's stored table definitions differed from the entities and were replaced. Never set for a single file, which stores none. */
    definitionsUpdated: boolean;
  };
  port: number;
  /** Generated files and whether this run changed them. */
  generated: { file: string; changed: boolean }[];
  /** `command` restarts on source changes; `runCommand` starts the sandbox once. */
  script: { name: string; command: string; runCommand: string; status: "added" | "updated" | "present" | "different" };
  warnings: string[];
}

const SOURCE_FILE = /\.(ts|cts|mts|js|cjs|mjs)$/;

function slashes(path: string): string {
  return path.replaceAll("\\", "/");
}

/** Source text without comments, so that commented-out code is not detected. */
function withoutComments(source: string): string {
  return source.replace(/\/\*[\s\S]*?\*\//g, "").replace(/(^|\s)\/\/.*$/gm, "$1");
}

function writeIfChanged(file: string, text: string): boolean {
  if (existsSync(file) && readFileSync(file, "utf8") === text) {
    return false;
  }
  writeFileSync(file, text);
  return true;
}

/**
 * The entry point of a NestJS project in `cwd`, when none is given: the one
 * `nest-cli.json` names, or `src/main.ts`. The file may not be there.
 */
export function defaultNestEntry(cwd: string): string {
  let sourceRoot = "src";
  let entryFile = "main";
  try {
    const nestCli = JSON.parse(readFileSync(join(cwd, "nest-cli.json"), "utf8"));
    sourceRoot = typeof nestCli.sourceRoot === "string" ? nestCli.sourceRoot : sourceRoot;
    entryFile = typeof nestCli.entryFile === "string" ? nestCli.entryFile : entryFile;
  } catch {
    // No nest-cli.json: use the NestJS defaults.
  }
  return join(cwd, sourceRoot, `${entryFile}.ts`);
}

/**
 * Checks that the entry point is one the sandbox can run unchanged, and
 * names its root module. The sandbox runs the entry point itself, so these
 * checks only need to find what would make that impossible.
 */
function inspectEntry(entry: string, port: number): { rootModule: InitNestResult["rootModule"]; warnings: string[] } {
  const source = withoutComments(readFileSync(entry, "utf8"));
  const unsupported = (found: string, consequence: string): never => {
    throw new NestSandboxError(`${entry} ${found}. ${consequence}`);
  };
  if (/\bNestFactory\s*\.\s*createMicroservice\b/.test(source)) {
    unsupported("creates a microservice with NestFactory.createMicroservice()", "Only HTTP applications created with NestFactory.create() are supported.");
  }
  const create = /\bNestFactory\s*\.\s*create\s*(?:<[^>()]*>)?\s*\(\s*([A-Za-z_$][\w$]*)/.exec(source);
  if (create === null) {
    unsupported(
      "does not call NestFactory.create(<RootModule>)",
      "Pass the file that creates the application; an entry point that delegates this to another file or builds the module dynamically is not supported.",
    );
  }
  if (!/\.\s*listen\s*\(/.test(source)) {
    unsupported("does not call app.listen()", "The sandbox takes over that call to listen on its own port; applications that start their HTTP server another way are not supported.");
  }
  const literalPort = /\.\s*listen\s*\(\s*(\d+)\s*[,)]/.exec(source);
  if (literalPort !== null && Number(literalPort[1]) === port) {
    unsupported(`listens on port ${port}`, "Choose a different sandbox port with --port.");
  }

  const name = (create as RegExpExecArray)[1] as string;
  const imported =
    new RegExp(`import\\s*(?:[\\w$]+\\s*,\\s*)?\\{[^}]*\\b${name}\\b[^}]*\\}\\s*from\\s*["']([^"']+)["']`).exec(source) ??
    new RegExp(`import\\s+${name}\\s+from\\s*["']([^"']+)["']`).exec(source) ??
    new RegExp(`\\b${name}\\b[^;\\n]*=\\s*require\\(\\s*["']([^"']+)["']`).exec(source);

  const warnings: string[] = [];
  if (/\.\s*connectMicroservice\s*\(/.test(source)) {
    warnings.push("The entry point calls connectMicroservice(); the sandbox does not replace message transports, so they connect as in the original application.");
  }
  return { rootModule: { name, from: imported?.[1] }, warnings };
}

/** Source files under `directory` that set up TypeORM's root module. */
function findTypeormRoots(directory: string): string[] {
  return readdirSync(directory, { recursive: true, encoding: "utf8" })
    .filter((name) => SOURCE_FILE.test(name) && !/\.d\.[cm]?ts$/.test(name) && !name.split(/[\\/]/).includes("node_modules"))
    .sort()
    .filter((name) => /\bTypeOrmModule\s*\.\s*forRoot(Async)?\s*\(/.test(withoutComments(readFileSync(join(directory, name), "utf8"))));
}

/** Creates the single-file database, or adds the collections it does not have yet; existing content is kept. */
function writeDatabaseFile(file: string, result: ImportResult): InitNestResult["database"] {
  let document: Record<string, any>;
  let addedCollections: string[];
  const created = !existsSync(file);
  if (created) {
    document = toDatabaseDocument(result);
    addedCollections = result.collections.map((collection) => collection.name);
  } else {
    try {
      document = JSON.parse(readFileSync(file, "utf8"));
    } catch (cause) {
      throw new NestSandboxError(`${file} exists and is not valid JSON. Fix or remove it, or choose another file with --out.`, { cause });
    }
    const data = document?.data;
    if (typeof data !== "object" || data === null || Array.isArray(data)) {
      throw new NestSandboxError(`${file} exists and is not a sandbox database file (no "data" object). Choose another file with --out.`);
    }
    addedCollections = result.collections.map((collection) => collection.name).filter((name) => !Object.hasOwn(data, name));
    for (const name of addedCollections) {
      data[name] = [];
    }
  }
  if (addedCollections.length > 0) {
    const text = `${JSON.stringify(document, null, 2)}\n`;
    // The file must be one the sandbox will accept.
    assertWithinSizeLimit(Buffer.byteLength(text), DEFAULT_MAX_FILE_SIZE_MB * 1024 * 1024, "save");
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, text);
  }
  return { file, format: "file", created, addedCollections, definitionsUpdated: false };
}

/**
 * Creates the database directory with an empty table per entity, or brings an
 * existing one in line with the entities: tables it does not have yet are
 * added, and the stored table definitions are replaced when they differ.
 * Rows are kept, and a directory that needs neither is not written to.
 */
async function writeDatabaseDirectory(path: string, result: ImportResult, maxFileSizeMb: number | undefined): Promise<InitNestResult["database"]> {
  const names = result.collections.map((collection) => collection.name);
  // A directory holds what the columns are in the database the entities were written for, and the enumerated types they are of (D-040).
  const { tables: schema, types } = databaseSchema(result.collections);
  const exists = existsSync(path);
  const isDatabase = exists && existsSync(join(path, "manifest.json"));
  if (exists && !isDatabase && readdirSync(path).length > 0) {
    throw new NestSandboxError(`${path} exists and is not a database directory (it has no manifest.json). Choose another path with --out.`);
  }
  if (!isDatabase) {
    await createDatabase(path, { collections: Object.fromEntries(names.map((name) => [name, []])), schema, ...(types.enums.length > 0 && { types }) }, { format: "directory" });
    return { file: path, format: "directory", created: true, addedCollections: names, definitionsUpdated: false };
  }

  try {
    const storage = new DirectoryStorageAdapter(path, { maxFileSizeMb });
    const state = await storage.load();
    const addedCollections = names.filter((name) => !Object.hasOwn(state.collections, name));
    // Definitions of tables that are not entities here are kept as they are.
    const definitionsUpdated = !sameDatabaseSchema({ tables: storage.schema, types: storage.types }, { tables: mergeSchemas(storage.schema, schema), types: mergeTypes(storage.types, types) });
    if (addedCollections.length > 0 || definitionsUpdated) {
      for (const name of addedCollections) {
        state.collections[name] = [];
      }
      storage.describe(schema, types);
      storage.saveSync(state);
    }
    return { file: path, format: "directory", created: false, addedCollections, definitionsUpdated };
  } catch (cause) {
    const message = cause instanceof Error ? cause.message : String(cause);
    // A database in another format says itself what to do about it.
    throw new NestSandboxError(cause instanceof DatabaseFormatError ? message : `${message} Fix or remove it, or choose another path with --out.`, { cause });
  }
}

/** Adds the `sandbox` script to package.json unless a script of that name exists. */
function addScript(root: string): InitNestResult["script"] {
  const file = join(root, "package.json");
  const text = readFileSync(file, "utf8");
  const manifest = JSON.parse(text);
  const existing: unknown = manifest.scripts?.[SCRIPT_NAME];
  const script = { name: SCRIPT_NAME, command: SCRIPT_COMMAND, runCommand: RUN_COMMAND };
  // The script an earlier version of init-nest wrote is replaced; anything else is the user's own.
  if (existing !== undefined && existing !== RUN_COMMAND) {
    return { ...script, status: existing === SCRIPT_COMMAND ? "present" : "different" };
  }
  manifest.scripts = { ...manifest.scripts, [SCRIPT_NAME]: SCRIPT_COMMAND };
  // Keep the file's own indentation and line endings.
  const indent = /^[ \t]+(?=")/m.exec(text)?.[0] ?? "  ";
  const newline = text.includes("\r\n") ? "\r\n" : "\n";
  writeFileSync(file, `${JSON.stringify(manifest, null, indent)}${text.endsWith("\n") ? "\n" : ""}`.replaceAll("\n", newline));
  return { ...script, status: existing === undefined ? "added" : "updated" };
}

/**
 * Prepares an existing NestJS + TypeORM project to run a second, sandbox
 * server next to the original one. Nothing in the application's sources is
 * changed: this writes the database, two small files under
 * `.local-db-sandbox/`, and a `sandbox` script in package.json.
 *
 * A new project gets a database directory. A project that already has a
 * database keeps it, in the format it has: nothing is converted here (see
 * `convertDatabase`).
 */
export async function initNest(options: InitNestOptions = {}): Promise<InitNestResult> {
  const cwd = resolve(options.cwd ?? process.cwd());
  const entry = options.entry === undefined ? defaultNestEntry(cwd) : resolve(cwd, options.entry);
  if (!existsSync(entry)) {
    throw new NestSandboxError(`Entry point does not exist: ${entry}${options.entry === undefined ? ". Pass the path of the file that starts the application." : ""}`);
  }
  const root = findProjectRoot(dirname(entry));
  const directory = join(root, SANDBOX_DIRECTORY);
  const configFile = join(directory, "sandbox.config.json");

  let previous: Partial<NestSandboxConfig> = {};
  try {
    previous = JSON.parse(readFileSync(configFile, "utf8"));
  } catch {
    // First run, or an unreadable config that is about to be replaced.
  }
  const port = options.port ?? (typeof previous.port === "number" ? previous.port : DEFAULT_NEST_SANDBOX_PORT);
  if (!Number.isInteger(port) || port < 0 || port > 65535) {
    throw new NestSandboxError("The sandbox port must be an integer from 0 to 65535.");
  }
  const configured = typeof previous.database === "string" ? resolve(directory, previous.database) : undefined;
  const singleFile = join(root, SINGLE_FILE_DATABASE);
  const database =
    options.database !== undefined
      ? resolve(cwd, options.database)
      : (configured ??
        // A project that has a single-file database and no directory keeps using the file.
        (existsSync(singleFile) && !existsSync(join(root, DEFAULT_DATABASE)) ? singleFile : join(root, DEFAULT_DATABASE)));

  const { rootModule, warnings } = inspectEntry(entry, port);

  const projectRequire = createRequire(join(root, "package.json"));
  for (const name of ["@nestjs/core", "@nestjs/typeorm", "typeorm"]) {
    try {
      projectRequire.resolve(name);
    } catch (cause) {
      throw new NestSandboxError(`"${name}" is not installed in ${root}. init-nest is for NestJS applications that use @nestjs/typeorm.`, { cause });
    }
  }
  const sources = dirname(entry);
  const typeormRoots = findTypeormRoots(sources).map((name) => slashes(relative(root, join(sources, name))));
  if (typeormRoots.length === 0) {
    throw new NestSandboxError(
      `No TypeOrmModule.forRoot() or forRootAsync() call was found under ${sources}. ` +
        "The sandbox replaces that call; applications that create their DataSource another way are not supported.",
    );
  }

  const entities = options.entities === undefined ? sources : resolve(cwd, options.entities);
  const imported = importTypeorm(entities);
  const inRoot = (path: string): string => slashes(relative(root, path));
  const databaseResult =
    databaseFormatFor(database) === "directory"
      ? await writeDatabaseDirectory(database, imported, typeof previous.maxFileSizeMb === "number" ? previous.maxFileSizeMb : undefined)
      : writeDatabaseFile(database, imported);
  if (databaseResult.created && configured !== undefined && configured !== database && existsSync(configured)) {
    // Pointing the project at a new database does not move its data.
    warnings.push(
      `The sandbox now uses ${inRoot(database)}, which is new and empty. The rows of ${inRoot(configured)} were not copied; ` +
        `"local-db-sandbox convert ${inRoot(configured)} --out ${inRoot(database)} --force" copies them.`,
    );
  }

  mkdirSync(directory, { recursive: true });
  const config: NestSandboxConfig = {
    entry: slashes(relative(directory, entry)),
    database: slashes(relative(directory, database)),
    port,
    ...(previous.persistence !== undefined && { persistence: previous.persistence }),
    ...(previous.sqlLog !== undefined && { sqlLog: previous.sqlLog }),
    ...(previous.sqlPreviewRows !== undefined && { sqlPreviewRows: previous.sqlPreviewRows }),
    ...(previous.logSql !== undefined && { logSql: previous.logSql }),
    ...(previous.watch !== undefined && { watch: previous.watch }),
    ...(previous.maxFileSizeMb !== undefined && { maxFileSizeMb: previous.maxFileSizeMb }),
  };
  const serverFile = join(directory, "sandbox.server.ts");
  const generated = [
    { file: serverFile, changed: writeIfChanged(serverFile, SERVER_FILE) },
    { file: configFile, changed: writeIfChanged(configFile, `${JSON.stringify(config, null, 2)}\n`) },
  ];

  return {
    root,
    entry: inRoot(entry),
    rootModule,
    typeormRoots,
    entities: inRoot(entities) || ".",
    import: imported,
    database: { ...databaseResult, file: inRoot(database) },
    port,
    generated: generated.map((entry) => ({ ...entry, file: inRoot(entry.file) })),
    script: addScript(root),
    warnings,
  };
}
